def ingest():
    db = get_aircraft_database()
    added = []
    skipped = []
    errors = []

    for item in NEW_MOTOGLIDERS:
        aid = item["id"]
        existing = db.get_by_id(aid)
        if existing:
            skipped.append(aid)
            continue

        try:
            res = db.create(item)
            p_or_t = f"{res['p_kw']} kW" if res.get('p_kw') is not None else f"{res.get('t_kn')} kN"
            added.append((res["id"], res["model"], p_or_t, res["ld_max"]))
            print(f"Added: {res['id']} - {res['model']} (Propulsion={p_or_t}, L/D={res['ld_max']})")
        except Exception as e:
            errors.append((aid, str(e)))
            print(f"Error adding {aid}: {e}")

    print(f"\nResult: {len(added)} added, {len(skipped)} skipped, {len(errors)} errors.")
    return added, skipped, errors


if __name__ == "__main__":
    ingest()

