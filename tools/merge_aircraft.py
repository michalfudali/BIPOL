def ingest():
    db = get_aircraft_database()
    added = []
    skipped = []
    updated = []

    for item in NEW_AIRCRAFT:
        aid = item["id"]
        # Check if exists
        existing = db.get_by_id(aid)
        if existing:
            skipped.append(aid)
            continue

        try:
            res = db.create(item)
            added.append((res["id"], res["model"], res["aircraft_type"]))
            print(f"Added: {res['id']} - {res['model']} ({res['aircraft_type']})")
        except Exception as e:
            print(f"Error adding {aid}: {e}")

    print(f"\nSummary: {len(added)} added, {len(skipped)} skipped, {len(updated)} updated.")
    return added


if __name__ == "__main__":
    ingest()
